//! Word theme-language recovery for Windows supplemental locales.

use std::sync::Arc;

pub(super) fn resolve(language: &str, format_locale: Option<&str>) -> Arc<str> {
  // Word imports themeFontLang through Windows language identifiers. Names
  // without a permanent LCID share LOCALE_CUSTOM_UNSPECIFIED (0x1000), and
  // theme font selection recovers the user's regional format language for
  // that identifier. It does not use the Office UI, authoring language, or
  // paragraph language. Missing/empty/unknown names take a different path;
  // do not treat every unrecognized BCP-47 name as a custom Windows locale.
  //
  // MS-LCID sections 2.2.1 and Appendix A; native opposite-format controls
  // select Calibri, PMingLiU and Yu Gothic for en-US, zh-TW and ja-JP.
  // Resolve once at document import, before selecting supplemental faces.
  let custom = CUSTOM_LOCALES
    .binary_search_by(|candidate| {
      candidate
        .bytes()
        .cmp(language.bytes().map(|byte| byte.to_ascii_lowercase()))
    })
    .is_ok();
  Arc::from(if custom {
    format_locale.unwrap_or(language)
  } else {
    language
  })
}

