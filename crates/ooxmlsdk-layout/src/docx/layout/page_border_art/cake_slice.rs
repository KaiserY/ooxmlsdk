pub(super) fn paint(page: &mut Page, coordinates: ArtPageCoordinates, tile: ArtTile) {
  let mut items = Vec::with_capacity(POLYGONS.len());
  for (source, color) in POLYGONS.into_iter().zip(COLORS) {
    let points: Vec<_> = source
      .iter()
      .map(|&(x, y)| {
        coordinates.point(
          f64::from(tile.x) + f64::from(x) * f64::from(tile.width) / WINDOW[0],
          f64::from(tile.y) + f64::from(y) * f64::from(tile.height) / WINDOW[1],
          false,
        )
      })
      .collect();
    let mut commands = Vec::with_capacity(points.len() + 1);
    commands.push(PathCommand::MoveTo(points[0]));
    commands.extend(points[1..].iter().copied().map(PathCommand::LineTo));
    commands.push(PathCommand::Close);
    let bounds =
      super::super::drawing_path_bounds(&commands).expect("finite built-in CakeSlice motif");
    items.push(PageItem::path(PathItem {
      bounds,
      points,
      commands,
      closed: true,
      fill: Fill::Solid(color),
      stroke: None,
    }));
  }
  let start = coordinates.point(f64::from(tile.x), f64::from(tile.y), false);
  let end = coordinates.point(
    f64::from(tile.x + tile.width),
    f64::from(tile.y + tile.height),
    false,
  );
  page.items.push(PageItem::CompositingGroup {
    items,
    opacity: 1.0,
    clip: Some(crate::model::common_rect(
      start.x.0,
      start.y.0,
      end.x.0 - start.x.0,
      end.y.0 - start.y.0,
    )),
  });
}
