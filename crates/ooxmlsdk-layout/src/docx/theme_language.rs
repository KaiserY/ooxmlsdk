#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn custom_theme_languages_follow_regional_format() {
    assert!(CUSTOM_LOCALES.windows(2).all(|pair| pair[0] < pair[1]));
    for language in ["en-NL", "EN-nl", "en-150", "af-NA", "nl-SR"] {
      for format in ["zh-CN", "zh-TW", "ja-JP", "en-US"] {
        assert_eq!(resolve(language, Some(format)).as_ref(), format);
      }
      assert_eq!(resolve(language, None).as_ref(), language);
    }
  }

  #[test]
  fn ordinary_and_unknown_theme_languages_preserve_their_slots() {
    for language in [
      "en-US", "nl-NL", "zh-SG", "ja-JP", "ar-SA", "en", "", "xx-YY",
    ] {
      assert_eq!(resolve(language, Some("zh-CN")).as_ref(), language);
    }
  }
}
