pub(super) fn paint(
  page: &mut Page,
  coordinates: ArtPageCoordinates,
  x: i32,
  y: i32,
  width: i32,
  height: i32,
) {
  let mut items = Vec::with_capacity(POLYGONS.len());
  for (index, source) in POLYGONS.iter().enumerate() {
    let points: Vec<_> = source
      .iter()
      .map(|&(px, py)| {
        coordinates.point(
          f64::from(x) + f64::from(px) * f64::from(width) / WINDOW[0],
          f64::from(y) + f64::from(py) * f64::from(height) / WINDOW[1],
          false,
        )
      })
      .collect();
    let mut commands = Vec::with_capacity(points.len() + 1);
    commands.push(PathCommand::MoveTo(points[0]));
    commands.extend(points[1..].iter().copied().map(PathCommand::LineTo));
    commands.push(PathCommand::Close);
    let fill = match index {
      0..3 => Color {
        r: 0,
        g: 153,
        b: 0,
        a: 255,
      },
      3..6 => Color {
        r: 194,
        g: 52,
        b: 133,
        a: 255,
      },
      _ => Color {
        r: 255,
        g: 255,
        b: 255,
        a: 255,
      },
    };
    let stroke = (3..6).contains(&index).then(|| {
      // Native LOGPEN: PS_INSIDEFRAME, width146 logical units. Its physical
      // width uses the resource mapping and the same fixed-output ticks as
      // other art; Word's existing0.14pt minimum applies independently.
      let printer_width = 146.0 * f64::from(width) / WINDOW[0];
      Stroke {
        width: Pt((((printer_width * 5.0).round() * DOT / 5.0) as f32).max(0.14)),
        color: Color {
          r: 102,
          g: 0,
          b: 26,
          a: 255,
        },
        cap: Some(StrokeCap::Flat),
        join: Some(StrokeJoin::Round),
        alignment: Some(StrokeAlignment::Inside),
        ..Stroke::default()
      }
    });
    let bounds = super::super::drawing_path_bounds(&commands).expect("finite built-in motif");
    items.push(PageItem::path(PathItem {
      bounds,
      points,
      commands,
      closed: true,
      fill: Fill::Solid(fill),
      stroke,
    }));
  }
  let start = coordinates.point(f64::from(x), f64::from(y), false);
  let end = coordinates.point(f64::from(x + width), f64::from(y + height), false);
  page.items.push(PageItem::CompositingGroup {
    items,
    opacity: 1.0,
    clip: Some(crate::model::common_rect(
      start.x.0,
      start.y.0,
      end.x.0 - start.x.0,
      end.y.0 - start.y.0,
    )),
  });
}
