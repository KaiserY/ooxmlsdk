//! Word's integer line metrics and positioned printer baseline.
use crate::common;

const IDEAL: f64 = 4096.0;
const SOURCE_DPI: i64 = 294_912;
const TARGET_DPI: i64 = 600;

fn mul_div(value: i64, multiplier: i64, divisor: i64) -> i64 {
  value.signum() * ((value.abs() * multiplier + divisor / 2) / divisor)
}

fn device(value: i64) -> i64 {
  mul_div(value, TARGET_DPI, SOURCE_DPI)
}

#[derive(Clone, Copy, Debug, PartialEq)]
struct Line {
  height: i64,
  before: i64,
  after: i64,
  ascent: i64,
  descent: i64,
}

fn fit(height: i64, below: i64, before: i64, after: i64) -> Line {
  let mut line = Line {
    height: device(height),
    before: device(before),
    after: device(after),
    ascent: device(height - before - below),
    descent: device(below - after),
  };
  let mut remainder = line.height - line.before - line.after - line.ascent - line.descent;
  // Word realizes the individual components, then distributes their rounding
  // residue. Native WWLIB 34144 / 2f8200 observations distinguish the order:
  // shrink trailing spacing, leading spacing, then the font component with
  // the larger round-trip excess. Growth starts with ascent, then descent.
  let shrink_font = |line: &mut Line| {
    let restore = |value| mul_div(value, SOURCE_DPI, TARGET_DPI);
    if line.descent > 0 && restore(line.descent) - below >= restore(line.ascent) + below - height {
      line.descent -= 1;
    } else {
      line.ascent -= 1;
    }
  };
  if remainder > 0 {
    line.ascent += 1;
    remainder -= 1;
    if remainder > 0 {
      line.descent += 1;
      remainder -= 1;
    }
    line.ascent += remainder;
  } else if remainder < 0 {
    if line.after > 0 {
      line.after -= 1;
    } else if line.before > 0 {
      line.before -= 1;
    } else {
      shrink_font(&mut line);
    }
    remainder += 1;
    if remainder < 0 {
      if line.before > 0 {
        line.before -= 1;
      } else if line.after > 0 {
        line.after -= 1;
      } else {
        shrink_font(&mut line);
      }
      remainder += 1;
    }
    // The independent nearest conversions above differ by at most two cells;
    // retain the native order for a larger imposed compression as well.
    if remainder < 0 {
      for value in [
        &mut line.after,
        &mut line.before,
        &mut line.descent,
        &mut line.ascent,
      ] {
        let consumed = (*value).min(-remainder);
        *value -= consumed;
        remainder += consumed;
      }
    }
  }
  line
}

pub fn realize(metrics: common::WordprocessingLineMetrics, origin_y: f32) -> Option<f32> {
  let ideal = |value: f64| {
    let units = (value * IDEAL).round();
    (units.is_finite() && units.abs() <= f64::from(i32::MAX)).then_some(units as i64)
  };
  let height = ideal(f64::from(metrics.height_pt))?;
  let below = ideal(f64::from(metrics.baseline_from_bottom_pt))?;
  let before = ideal(f64::from(metrics.spacing_before_pt))?;
  let after = ideal(f64::from(metrics.spacing_after_pt))?;
  if [before, after, height - before - below, below - after]
    .into_iter()
    .any(|v| v < 0)
  {
    return None;
  }
  let bottom = ideal(f64::from(origin_y) + f64::from(metrics.bottom_offset_pt))?;
  let line = fit(height, below, before, after);
  // At paint Word measures the actual line interval by converting both ends.
  // Its height correction changes the distance below the baseline, capped by
  // the remaining trailing spacing (WWLIB bd72b4), before subtracting that
  // distance from the independently converted absolute bottom (267e95).
  let positioned_height = device(bottom) - device(bottom - height);
  let adjusted_below =
    line.descent + line.after + (positioned_height - line.height).max(-line.after);
  Some(((device(bottom) - adjusted_below) as f64 * 72.0 / TARGET_DPI as f64) as f32)
}

